   public void onActivate() {
      if (this.mc.player == null) {
         this.toggle();
      } else if ((Boolean)this.whisperMode.get() && !(Boolean)this.randomWhisper.get() && ((String)this.targetPlayer.get()).trim().isEmpty()) {
         ChatUtils.info(": chatModeneedTarget Player", new Object[0]);
         this.toggle();
      } else {
         this.lastTime = System.currentTimeMillis();
         ChatUtils.info("AutoTextAlreadyMove", new Object[0]);
      }
   }


   @EventHandler
   private void onTick(Pre event) {
      if (this.mc.player != null && this.mc.getNetworkHandler() != null) {
         if (!(System.currentTimeMillis() - this.lastTime < (Double)this.delay.get() * 1000.0)) {
            this.lastTime = System.currentTimeMillis();

            try {
               String msg = this.getRandomMessage();
               if ((Integer)this.randomLength.get() > 0) {
                  String randomStr = this.generateRandomString((Integer)this.randomLength.get());
                  if (!randomStr.isEmpty()) {
                     msg = msg + " " + randomStr;
                  }
               }

               String finalContent;
               if ((Boolean)this.whisperMode.get()) {
                  String target = this.getTargetPlayer();
                  if (target == null) {
                     ChatUtils.warning("CannotGetTarget Player, pastThisTimesSend.", new Object[0]);
                     return;
                  }

                  finalContent = "/" + ((String)this.whisperCmd.get()).trim() + " " + target + " " + msg;
               } else {
                  finalContent = msg;
               }

               this.sendMessage(finalContent);
            } catch (Exception var5) {
               ChatUtils.error("Send:" + var5.getMessage(), new Object[0]);
            }
         }
      }
   }

   private String getRandomMessage() {
      return this.messages.isEmpty() ? (String)this.defaultMessage.get() : this.messages.get(this.random.nextInt(this.messages.size()));
   }

   private String getTargetPlayer() {
      if ((Boolean)this.randomWhisper.get()) {
         Collection<PlayerListEntry> players = this.mc.getNetworkHandler().getPlayerList();
         ArrayList<PlayerListEntry> list = new ArrayList<>(players);
         if (list.isEmpty()) {
            return null;
         } else {
            PlayerListEntry playerListEntry = list.get(this.random.nextInt(list.size()));
            if ((Boolean)this.checkSelf.get()) {
               for (int attempts = 0;
                  Objects.equals(playerListEntry.getProfile().name(), this.mc.player.getName().getString());
                  playerListEntry = list.get(this.random.nextInt(list.size()))
               ) {
                  if (attempts > 50) {
                     return null;
                  }

                  attempts++;
               }
            }

            return playerListEntry.getProfile().name();
         }
      } else {
         return ((String)this.targetPlayer.get()).trim();
      }
   }

   private void sendMessage(String content) {
      if (!(Boolean)this.commandMode.get() && !content.startsWith("/")) {
         this.mc.getNetworkHandler().sendChatMessage(content);
      } else {
         String cmd = content.startsWith("/") ? content.substring(1) : content;
         this.mc.getNetworkHandler().sendChatCommand(cmd);
      }
   }

   private String generateRandomString(int length) {
      if (length <= 0) {
         return "";
      } else {
         StringBuilder sb = new StringBuilder(length);

         for (int i = 0; i < length; i++) {
            int index = this.random.nextInt("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz".length());
            sb.append("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz".charAt(index));
         }

         return sb.toString();
      }
   }
